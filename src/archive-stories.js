export function archiveSceneLines(s, g) {
  const replacements = !g.world?.beats?.irene_sera_wake && UNAWAKENED_PARAGRAPHS[s.id];
  const clue = OPTIONAL_CLUE_PARAGRAPHS[s.id];
  return s.lines.map((line, i) => {
    if (clue && !g.world?.found?.[clue.need] && clue.lines[i] != null) return clue.lines[i];
    return replacements?.[i] ?? line;
  });
}

// プレイ順が枝分かれしても、序章・章ごとの流れで読める。既読・知らせ済みは G.journal (src/journal.js)。
export function archiveStories(g) {
  return ARCHIVE_STORIES.filter(s => s.available(g)).sort((a, b) => a.chapter - b.chapter || ARCHIVE_STORIES.indexOf(a) - ARCHIVE_STORIES.indexOf(b)).map(s => ({ ...s, lines: archiveSceneLines(s, g) }));
}
