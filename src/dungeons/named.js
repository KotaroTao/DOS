//              全滅で失ったら、次に倒した時にまた落とす (G.named.trophy は持ち帰って初めて残る)
// 層を足すときは、その層の強敵2体をここに1行ずつ足し、world.js の縄張りと catalog/named.js の首級を書く。
// id は魔物の id (保存される)。並びは図鑑の並び。
