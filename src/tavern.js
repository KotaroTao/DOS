// 台帳の検査 (読み込み時): id の重複・種類・区分の誤り
{
  const seen = new Set();
  for (const t of TAVERN_TALKS) {
    if (!t.id || seen.has(t.id)) throw new Error(`tavern: id が無いか重複している: ${t.id}`);
    seen.add(t.id);
    if (!["chat", "tip", "lore"].includes(t.k)) throw new Error(`tavern: 種類の誤り: ${t.id}`);
    if (t.k === "tip" && !TIP_CATS.includes(t.cat)) throw new Error(`tavern: 心得の区分の誤り: ${t.id}`);
    if (t.who && t.who.some((w) => !TAVERN_SPEAKERS.some((s) => s.type === w))) throw new Error(`tavern: 肩書きの誤り: ${t.id}`);
  }
}

// 居合わせる者たちを選ぶ (game.js が解放の判定 allowed(req) と、聞いた話 heard を渡す)。
// 一人ずつ話の種類を引く: 雑談 4 : 心得 4 : 言い伝え 2。同じ種類の中では、まだ聞いていない心得・言い伝えを3倍選びやすくする。
// 心得が一つも出ない顔ぶれにはしない (心得が残っていれば、最後の一人を心得にする)
const KIND_W = [["chat", 4], ["tip", 4], ["lore", 2]];
export function pickTavernCrowd({ allowed = () => true, heard = {}, rand = Math.random } = {}) {
  const count = 3 + Math.floor(rand() * 3); // 3〜5名
  const speakers = [...TAVERN_SPEAKERS].sort(() => rand() - 0.5).slice(0, count);
  const pool = TAVERN_TALKS.filter((t) => allowed(t.req));
  const used = new Set();
  const fits = (t, sp) => !used.has(t.id) && (!t.who || t.who.includes(sp.type));
  const weight = (t) => (t.k !== "chat" && !heard[t.id] ? 3 : 1);
  const draw = (cands) => {
    let r = rand() * cands.reduce((a, t) => a + weight(t), 0);
    for (const t of cands) { if ((r -= weight(t)) < 0) return t; }
    return cands[cands.length - 1];
  };
  const crowd = [];
  speakers.forEach((sp, i) => {
    let kind = null;
    if (i === speakers.length - 1 && !crowd.some((m) => m.kind === "tip")) kind = "tip";
    else {
      let r = rand() * KIND_W.reduce((a, [, w]) => a + w, 0);
      for (const [k, w] of KIND_W) { if ((r -= w) < 0) { kind = k; break; } }
    }
    let cands = pool.filter((t) => t.k === kind && fits(t, sp));
    if (!cands.length) cands = pool.filter((t) => fits(t, sp));
    const talk = cands.length ? draw(cands) : null;
    if (talk) used.add(talk.id);
    crowd.push({ type: sp.type, icon: sp.icon, name: sp.names[Math.floor(rand() * sp.names.length)],
      line: talk ? talk.t : "「……」", kind: talk ? talk.k : "chat", id: talk ? talk.id : null });
  });
  return crowd;
}
