// 意匠 → 選びうる紋章
export const MOTIF_EMBLEM = {
  dragon: ["dragon"], star: ["star"], moon: ["moon"], sun: ["sun"], skull: ["skull"], bone: ["skull", "fang"],
  flame: ["flame"], frost: ["drop", "diamond"], wave: ["wave", "drop"], wind: ["wing", "bolt"], thunder: ["bolt"],
  leaf: ["tree", "leaf"], wing: ["wing"], holy: ["cross", "cross2", "sun"], blood: ["drop", "rose"], serpent: ["serpent"],
  beast: ["beast", "fang"], demon: ["horns", "skull", "eye"], eye: ["eye"], crown: ["crown"], rune: ["diamond", "eye", "star"],
  crystal: ["diamond"], chain: ["saltire"], thorn: ["rose", "saltire"],
};
export const PLAIN_EMBLEMS = ["cross", "cross2", "saltire", "star", "sun", "chevron", "diamond", "sword", "crown", "tree", "beast", "wing"];

// 紋章を押す: (x0, y0) が左上、mat = 地の素材、gem = 宝石の素材。flip = 左右反転
export function stamp(g, name, x0, y0, mat, gem, { flip = false, base = 2 } = {}) {
  const e = EMBLEMS[name];
  if (!e) return;
  const w = e[0].length;
  e.forEach((row, y) => {
    for (let x = 0; x < w; x++) {
      const ch = row[flip ? w - 1 - x : x];
      if (ch === ".") continue;
      const X = x0 + x, Y = y0 + y;
      if (ch === "*") g.set(X, Y, gem || mat, 3);
      else g.set(X, Y, mat, ch === "+" ? base + 1 : ch === "-" ? base - 1 : base);
    }
  });
}
export function pickEmblem(th) {
  const r = th.r;
  const c = [];
  for (const m of th.motifs) if (MOTIF_EMBLEM[m]) c.push(...MOTIF_EMBLEM[m]);
  if (c.length && r.chance(0.85)) return r.pick(c);
  return r.pick(PLAIN_EMBLEMS);
}
