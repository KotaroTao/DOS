export const BOND_GIFTS = {
  3: { souls: [["rare", 1]] },
  6: { embers: 1, souls: [["rare", 1]] },
  10: { embers: 1, souls: [["epic", 1]] },
  later: { embers: 1, souls: [["rare", 1]] },
};
export function bondGiftAt(count) {
  if (BOND_GIFTS[count]) return { tier: count === 3 ? 0 : count === 6 ? 1 : 2, gift: BOND_GIFTS[count] };
  if (count > 10 && count % 5 === 0) return { tier: 2, gift: BOND_GIFTS.later };
  return null;
}
export const TIP_RATE = 22; // 心付けの出る率 (%)
export const npcBondLabel = (n) => (n >= 10 ? "古なじみ" : n >= 6 ? "なじみ" : n >= 3 ? "顔なじみ" : n >= 1 ? "顔見知り" : null);

// 報告の語りを組む。q = 報告するフリークエスト、count = この依頼人への報告の回数 (今回を含む)、
// opt = { rand(n), tip: 心付けがあるか, bond: bondGiftAt の結果 }
// 返り値: 語りの行の配列 (「…」= 依頼人の言葉 / ── = 受け取りの要旨 / それ以外 = 地の文)
export function composeReport(q, count, opt = {}) {
  const rand = opt.rand || ((n) => Math.floor(Math.random() * n));
  const pick = (list) => list[rand(list.length)];
  const npc = npcOf(q.npc);
  const v = { name: npcCall(npc), ...(q.vars || {}) };
  const out = [];
  const opens = [...REPORT_OPEN, ...(REPORT_OPEN_BY_TYPE[q.type] || []).filter((t) => !/\{(mon|goal|dun|f|item)\}/.test(t) || q.vars)]
    .filter((t) => !(npc.title.includes("女将") && t.includes("女将"))); // 女将の依頼で「女将が奥を示す」は書かない
  out.push(fill(pick(opens), v));
  out.push(fill(q.done || DONE_FALLBACK[q.type] || "「確かに。」", v));
  if (opt.bond) out.push(npc.bond[Math.min(npc.bond.length - 1, opt.bond.tier)]);
  else out.push(pick(count >= 3 && rand(3) ? npc.regular : npc.thanks));
  if (opt.tip) out.push(pick(npc.tip));
  if (opt.bond) out.push(`──${npc.name}から、${npcBondLabel(count)}の礼を授かった。`);
  else if (rand(100) < 45) out.push(pick(REPORT_CLOSE.filter((t) => !(npc.title.includes("女将") && t.includes("女将")))));
  return out;
}

