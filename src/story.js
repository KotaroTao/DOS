// 迷宮の id・階 → その階の物語マスの鍵 (無ければ null)
export function storyCellAt(dungeonId, floor) {
  for (const k in STORY_CELLS) { const c = STORY_CELLS[k]; if (c.dungeon === dungeonId && c.floor === floor) return k; }
  return null;
}

