// 迷宮の初踏破の報告報酬 (難度 n で決まる)。主のいる迷宮は赤い魂が厚い
export function msqReward(n, boss = false) {
  const r = { gold: 80 + n * 22, soulPts: 30 + n * 6 };
  r.redSoul = boss ? 6 + Math.ceil(n / 5) * 2 : 2;
  return r;
}

