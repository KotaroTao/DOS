// メインストーリー「百の迷宮と、魂の王」── 師を捜す物語
//
// 主人公は操霊師オルドの弟子。王に仕えた師は一年前、迷宮へ降りたきり戻らなかった。
// 届いたのは一通の手紙 ──『ロアダルへ来い。館の灯を、絶やすな』。
// 師の館に灯る燭台は、師の魂に結ばれた灯。燃えているかぎり、師の魂はまだこの世のどこかにある。
// 館をあずかるイレーヌは、師が作った人業 (第一章の取水口で、そのことが明かされる)。
// 第二章「捨て砦」: 百年前に王都が見捨てた国境の砦。守備隊の魂は砦ごと「魂脈」に捧げられた。
// 師は砦の本丸の大穴から魂脈の根へ降りた。牢には歴代の操霊師の名、底にはセラの頭。
// 本丸の主の記憶で、砦を捨てた書状に王家の紋と宰相府の印があったと知り、王は自分こそが百年を生きた「先代」だと明かす。
// 第三章「魂脈の根」: 大穴の下は、魂が木になる地の底の森。魂脈は大樹の根だった。牢を抜けた師の師ヴェルナーの小屋、
// 根に裂かれたセラの胴。大樹の主の記憶で、師が根を断って幹の中へ入り、王都の玉座の真下へ登っていったと知る。
// 大樹を植えたのは宰相モルデン (三百年、根に水をやってきた庭師)。
// 第四章「王都の地下」: 王都の足元には、三百年前に一夜で沈んだ旧都と大神殿がある。若い神官モルデンが神殿の泉に大樹の苗を
// 植え、反対した神官王ごと旧都を水に沈めた。セラの脚が洗礼の大水槽の底で見つかり、館でセラが目を覚ます (仲間になる)。
// 神官王の記憶で、師が「心臓は樹液を煮詰める釜だ」と悟り、神殿の底の火の洞へ降りたと知る。
// 第五章「灼熱の洞」: 大樹の樹液を王の霊薬に煮詰める火の洞。釜の火は迷宮に呑まれた魂。業火の主の記憶で、モルデンは人ではなく
// 「最初の操霊師」が作った最初の人業だと明かされ、師は大釜の底の穴「奈落」へ落ちた (燭台の灯はまだ燃えている)。
//
// 迷宮は一本道ではない (src/dungeons/world.js の台帳)。物語は「どの迷宮で何を見つけたか」で進む:
//   ・物語マス (STORY_CELLS) … 迷宮の決まった階に必ず置かれる、師の手がかり。踏むと一枚絵つきで語られる
//   ・主の記憶 (BOSS_MEMORIES) … 主を討った直後、ほどけた魂の記憶が流れ込む
//   ・踏破の報告 (REPORTS) … 初めて踏破した迷宮を王に報告する。王は見たものを聞きたがる
//   ・館の語り (IRENE_BEATS) … 手がかりを持ち帰ると、館でイレーヌが語る
// 分岐は無い。どの順で迷宮を巡っても、語りが筋を外れないように書く (条件で一言だけ替える所はある)。
//
// 物語の行の書式 (ui/story.js): 「…」= 王 (語り手 who の台詞) / イレーヌ「…」/ 宰相… / ──『…』= 手紙・手記 /
//   ── = 要旨 (新たな迷宮など) / それ以外 = 地の文。art = 一枚絵 (src/storyart.js) / who = 語り手 ("king"|"irene"|"none")
//
// 第十章「地底大空洞」(第一部の結び): 闘技場の穴の底に、濁った灯籠が降り積もった大空洞。宰相モルデンは三百年、捨てられた魂を拾い、
// 名をつけ、石窟に眠らせてきた。最奥の階段の前でモルデンと対決し、その記憶で、師オルドが迷宮を潜る本当の理由は「魂の王」になる
// ためだと明かされる (底に眠るものを手にした者は魂の王となり、この世のあらゆる命を思うままにできる)。
// 先の章の筋 (2026-10-11 ユーザーの指示): 第二部の最後の敵は師オルド。ただし師にも理由があり、物語は「正義とは何か・正しさとは
// 何か」を問う。師を悪と決めつけない — 祖の「触れるな」、モルデンの「言いつけを守る」、師の「命令では誰も救えない、巡りを書き換える」、
// イレーヌの「灯を絶やすな」を、どれも一理ある立場として書く。

