const ftom = (f) => Math.round(69 + 12 * Math.log2(f / 440));

// 旧声部 → 新しい楽器の割り当て (音域・音価・波形から推定)
function assign(v) {
  const ns = v.notes;
  const avgF = ns.reduce((a, n) => a + n[1], 0) / ns.length;
  const avgD = ns.reduce((a, n) => a + n[2], 0) / ns.length;
  const many = ns.length;
  const t = v.type;
  if (avgF < 125) {
    if (avgD >= 4) return [["lowstr", 0.42, { att: 1.2, rel: 1.5 }], ["drone", 0.3, { lp: 600 }]];
    if (t === "sawtooth") return [["spicc", 0.5, {}], ["lowstr", 0.22, { att: 0.05, rel: 0.3 }]];
    return [["pizz", 0.5, {}], ["lowstr", 0.2, { att: 0.08, rel: 0.4 }]];
  }
  if (avgF < 260 && avgD >= 4) return t === "sawtooth" ? [["organ", 0.3, {}]] : [["pad", 0.3, { lp: 1400 }], ["choirO", 0.22, {}]];
  if (avgF >= 900 && avgD <= 2) return [["celesta", 0.34, { dly: 0.25 }]];
  if (avgD <= 1.5 && many >= 10) return [["harp", 0.4, { dly: 0.15 }]];
  if (t === "sine" && avgD <= 3 && many <= 8) return [["bell", 0.3, { lp: 3000 }]];
  if (t === "sawtooth" && avgD >= 4) return [["organ", 0.3, {}]];
  if (t === "sawtooth") return [["brass", 0.45, {}]];
  if (avgF >= 700 && avgD <= 1.5) return [["celesta", 0.3, {}]];
  if (t === "sine" && avgF < 330) return [["choirO", 0.42, {}]];
  if (t === "sine") return [["choir", 0.36, {}], ["strings", 0.2, {}]];
  return [["strings", 0.42, {}]];
}

const CACHE = new Map();
export function legacySong(name) {
  const th = THEMES[name];
  if (!th) return null;
  if (CACHE.has(name)) return CACHE.get(name);
  // 1ステップ = 1拍として扱う
  const s = new Score({ name, bpm: 60 / th.stepDur, bpb: 4, loop: [0, th.loop / 4], gain: GAIN[name] || 1.4, fadeIn: 1.2,
    delay: { l: 3, r: 4.5, fb: 0.3, lp: 2200 } });
  th.voices.forEach((v, i) => {
    for (const [j, [inst, vol, o]] of assign(v).entries()) {
      const id = `v${i}_${j}`;
      const pan = ((i % 3) - 1) * 0.25;
      s.ch(id, { inst, vol: vol * Math.min(1.4, Math.max(0.6, v.vol / 0.03)), rev: inst === "bell" || inst === "celesta" ? 0.75 : 0.5, pan, human: 0.008, ...o });
      for (const [st, f, d] of v.notes) {
        const m = ftom(f);
        s.n(id, st, inst === "drone" ? m - 12 : m, d * 0.96, 0.62);
      }
    }
  });
  // 墓所の空気 (全ての旧テーマに薄く敷く)
  s.ch("air", { inst: "wind", vol: 0.16, bp: 500, bpq: 0.7, lfo: { rate: 0.05, depth: 200 }, rev: 0.4 });
  s.n("air", 0, 60, th.loop + 2, 0.6);
  const built = s.build();
  CACHE.set(name, built);
  return built;
}
