import assert from 'node:assert/strict';
import * as b from '../../src/bukon.js';
import {itemName} from '../../src/items.js';
const ghost={k:'flat_atk',lv:1,soulMemory:true},real={k:'flat_atk',lv:1};
const g={gold:100000,bukonStock:{},bukonProtected:{}};
b.stockAdd(g,ghost,9);b.stockAdd(g,real,2);
assert.equal(b.stockRows(g).filter(x=>x.soulMemory)[0].count,'9');
assert.equal(b.stockRows(g).filter(x=>!x.soulMemory)[0].count,'2');
assert(b.bukonName(ghost).endsWith('（幻）'));assert(!b.bukonName(real).includes('（幻）'));
assert.equal(itemName({name:'検証の薬',soulMemory:true}),'検証の薬（幻）');
const gear={slot:'weapon',rar:'lr',bukon:[]};
assert(b.attachBukon(g,gear,ghost));assert(gear.bukon[0].soulMemory);
assert(b.detachBukon(g,gear,0));assert.equal(g.bukonStock[b.bukonKey(ghost)],'9');
assert.equal(b.snapshotFusionPlan(g,[],real),null,'実物2個を幻の素材で合成しない');
assert.equal(b.fusionPlan(g,real.k,2),null,'旧合成でも幻を実物の素材にしない');
assert(b.applySnapshotFusion(g,[],ghost));
assert.equal(g.bukonStock['flat_atk:2:phantom'],'1');
assert.equal(g.bukonStock['flat_atk:1'],'2');
assert.equal(g.bukonStock['flat_atk:1:phantom'],'6');
b.stockAdd(g,real);assert(b.applySnapshotFusion(g,[],real));
assert.equal(g.bukonStock['flat_atk:2'],'1');assert.equal(g.bukonStock['flat_atk:2:phantom'],'1');
const memory={slot:'weapon',rar:'lr',soulMemory:true,bukon:[real]},fresh={slot:'weapon',rar:'lr',bukon:[]};
b.inheritBukon(g,memory,fresh);assert(fresh.bukon[0].soulMemory,'旧記憶の武魂を新規装備へ引き継いでも幻');
b.recoverBukon(g,fresh);assert.equal(g.bukonStock['flat_atk:1:phantom'],'7');
const worn={slot:'weapon',rar:'lr',bukon:[{...real}]};
b.inheritBukon(g,worn,memory);assert.equal(g.bukonStock['flat_atk:1'],'1','幻の装備への引継ぎで実物を失わない');
console.log('幻の武魂: 表示・着脱・引継ぎ・回収・合成後の由来保持・実物との合成分離 OK');
