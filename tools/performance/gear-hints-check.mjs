import assert from 'node:assert/strict';
import {createGearHints,gearHintStats} from '../../src/gear-hints.js';
const sleep=()=>new Promise(r=>setTimeout(r,280));
let instances=[];
globalThis.Worker=class {constructor(){instances.push(this);}postMessage(msg){this.msg=msg;}terminate(){this.stopped=true;}};
const doll={uid:1,alive:true,primary:1,base:{atk:1},equip:{},items:[]};
let paused=false,changes=0;
const hints=createGearHints(()=>({pool:[doll],targets:[doll],paused}),()=>changes++);
hints.read(doll);await sleep();const w=instances[0];
doll.base.atk=2;w.onmessage({data:{id:w.msg.id,values:[[1,true]]}});
assert.equal(changes,0);assert.equal(gearHintStats.cancelled,1);
await sleep();w.onmessage({data:{id:w.msg.id,values:[[1,true]]}});
assert.equal(changes,1);assert.equal(hints.read(doll),true);
doll.base.atk=3;await sleep();paused=true;hints.pause();assert(w.stopped);
w.onmessage({data:{id:w.msg.id,values:[[1,false]]}});assert.equal(changes,1);
globalThis.Worker=class {constructor(){throw Error('unavailable');}};
const unavailable=createGearHints(()=>({pool:[doll],targets:[doll],paused:false}),()=>{throw Error('同期代替を使った');});
assert.equal(unavailable.read(doll),false);await sleep();assert.equal(gearHintStats.failed,1);
console.log('古い結果の破棄・再計算・中断・Worker不可時の同期代替禁止 OK');
