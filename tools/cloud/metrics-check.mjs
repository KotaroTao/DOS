import assert from "node:assert/strict";
import { SaveMetrics, saveMetrics, utf8Bytes } from "../../src/save-metrics.js";
import { CloudSaveClient } from "../../src/cloud-save.js";
const disk = new Map();
const storage = { getItem: k => disk.get(k), setItem: (k,v) => disk.set(k,v) };
let now = 0;
const m = new SaveMetrics({storage, now: () => now});
now = 1000; m.record('save', {sent: utf8Bytes('日本語'), received: 3, ms: 200, status: 200, ok: true});
m.record('save', {sent: 9, ms: 16000, status: 503});
m.record('secret-operation', {sent: 999});
m.visibility(false); now += 9000; m.visibility(true); now += 1000;
m.trialTrigger(); m.trialSample('日本語'); m.persist();
const r = m.report();
assert.equal(r.visibleMs, 2000); assert.equal(r.operations.save.attempts, 2);
assert.equal(r.operations.save.sentBytes, 18); assert.equal(r.operations.save.failures, 1);
assert.deepEqual(r.operations.save.latencyBuckets, [0,1,0,0,0,1]);
assert.equal(r.trial.snapshotBytes, 9); assert.equal(Object.keys(r.operations).length, 1);
assert.equal(new SaveMetrics({storage,now:()=>now}).report().trial.samples, 1);
const broken = new SaveMetrics({storage:{setItem(){throw Error('容量不足');}}}); broken.persist(); assert.equal(broken.report().storageError, true);
m.clear(); assert.deepEqual(m.report().operations, {});
// 実際の送信経路: 失敗・再送・UTF-8本文を数え、認証APIは記録しない。
saveMetrics.clear();
let attempts = 0;
const response = '{"revision":1,"note":"記録"}';
const client = new CloudSaveClient({url:'https://example.invalid',anonKey:'secret-key',protocol:1},{storage,fetcher:async()=>{
  attempts++;
  if (attempts===1) return new Response('一時障害',{status:503});
  return new Response(response,{status:200});
}});
client.auth={access_token:'secret-token',expires_at:9999999999,user:{id:'secret-user'}};
const body={op:'save',snapshot:{name:'秘密の名前'}};
await assert.rejects(client.request(body)); await client.request(body);
const summary=saveMetrics.report();
assert.equal(summary.operations.save.attempts,2); assert.equal(summary.operations.save.successes,1);
assert.equal(summary.operations.save.sentBytes,2*utf8Bytes(JSON.stringify(body)));
assert.equal(summary.operations.save.receivedBytes,utf8Bytes('一時障害')+utf8Bytes(response));
await client.authRequest('recover',{email:'secret-email'});
assert.equal(saveMetrics.report().operations.save.attempts,2);
assert(!/secret|秘密/.test(JSON.stringify(summary)));
console.log('保存計測: UTF-8・表示時間・失敗/再送・認証と個人情報の除外・試遊サンプル・保管失敗 OK');

// 通信以外の待機も数値の集計だけを残し、段階名や本文の持ち込みを拒否する。
m.timing('commandQueue',120);m.timing('commandQueue',80);m.timing('commandCalculation',50);
m.timing('commandResult',900,4);m.timing('confirmedPlayback',400);m.timing('秘密の名前',1);m.timing('commandQueue',NaN);
const timing=m.report().timings;
assert.deepEqual(timing.commandQueue,{samples:2,totalMs:200,maxMs:120,confirmedActions:0});
assert.equal(timing.commandResult.confirmedActions,4);assert.equal(Object.keys(timing).length,4);
m.persist();assert.deepEqual(new SaveMetrics({storage,now:()=>now}).report().timings,timing);
console.log('体感の計測: 送信列待ち・並行計算・選択から結果表示・確定済み演出の区別と手数・数値のみの保管 OK');
m.data.timings={commandQueue:"壊れた計測"};assert.doesNotThrow(()=>m.timing('commandQueue',10));assert.equal(m.report().timings.commandQueue.samples,1);
